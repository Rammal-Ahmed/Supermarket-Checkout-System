print("=" * 40)
print("SUPERMARKET CHECKOUT SYSTEM".center(40))
print("=" * 40)
print()

products = int(input("How many products? "))

names = []
prices = []
quantities = []
item_totals = []
subtotal = 0

for i in range(products):
    print()
    print("Product", i + 1)
    name = input("Name: ")
    price = int(input("Price: "))
    qty = int(input("Quantity: "))

    total = price * qty

    names.append(name)
    prices.append(price)
    quantities.append(qty)
    item_totals.append(total)

    subtotal += total

# Discount is calculated once, after all products are entered
if subtotal >= 10000:
    discount = subtotal * 10 / 100
elif subtotal >= 5000:
    discount = subtotal * 5 / 100
else:
    discount = 0

final_bill = subtotal - discount

# Receipt
print()
print("================================")
print("         SUPERMARKET BILL")
print("================================")
print()

for i in range(len(names)):
    print(f"{names[i]:<10} {quantities[i]} x {prices[i]} = {item_totals[i]}")

print()
print("Subtotal:", subtotal)
print("Discount:", int(discount))
print("Final Bill:", int(final_bill))
print()
print("=" * 40)
print("TRANSACTION COMPLETED".center(40))
print("THANK U FOR SHOPPING..!".center(40))
print("SEE YOU IN THE NEXT REPOSITORIES..!".center(40))
print("=" * 40)